// Writes the server files for the live site into deploy/out/ (no dependencies):  node deploy/generate.mjs --domain averixa.pk --stores main,attire [--app /srv/shop/app]
//   Caddyfile (HTTPS, one block per shop / API / admin), ecosystem.config.cjs (pm2: every API, shop and the admin), hosts.txt (keeps the shops' own server-side calls inside the server),
//   stores.json (the chosen stores + the domain, for scripts/store-links.ts), admin-stores.json (the admin's store list), env/<app>.env.production (addresses baked into each Next.js build), apps.txt.
// Secrets are NOT written here: the pm2 file reads /srv/shop/secrets.env (made by deploy/server-setup.sh) when it starts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, "..");
const a = process.argv.slice(2), opt = (k, d = "") => (a.includes(`--${k}`) ? a[a.indexOf(`--${k}`) + 1] : d);
const domain = opt("domain").toLowerCase();
if (!/^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(domain)) throw new Error("usage: node deploy/generate.mjs --domain averixa.pk --stores main,attire");
const APP = opt("app", "/srv/shop/app");
const reg = JSON.parse(fs.readFileSync(path.join(root, "stores.json"), "utf8"));
const stores = opt("stores", "main,attire").split(",").map((w) => w.trim()).filter(Boolean).map((w) => { const s = reg.stores.find((x) => x.slug === w); if (!s) throw new Error(`unknown store "${w}"`); return s; });

const OUT = path.join(here, "out");
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "env"), { recursive: true });
const host = (s) => (s.subdomain ? `${s.subdomain}.${domain}` : domain);
const apiHost = (s) => (s.slug === "main" ? `api.${domain}` : `api-${s.slug}.${domain}`);
const dirOf = (s) => s.webDir ?? "web";
const redisDb = (s) => reg.stores.findIndex((x) => x.slug === s.slug);
const adminHost = `admin.${domain}`;

// ---- Caddy
const caddy = [`(common) {
  encode zstd gzip
  header {
    X-Content-Type-Options nosniff
    Referrer-Policy strict-origin-when-cross-origin
    -Server
  }
  @immutable path /_next/static/*
  header @immutable Cache-Control "public, max-age=31536000, immutable"
  @media path /cs/* /brand/* /areas/* /kk/*
  header @media Cache-Control "public, max-age=86400"
}
`, `www.${domain} {\n  redir https://${domain}{uri} permanent\n}\n`];
for (const s of stores) {
  caddy.push(`${host(s)} {\n  import common\n  reverse_proxy 127.0.0.1:${s.webPort}\n}\n`);
  caddy.push(`${apiHost(s)} {\n  encode zstd gzip\n  reverse_proxy 127.0.0.1:${s.apiPort}\n}\n`);
}
caddy.push(`${adminHost} {\n  import common\n  reverse_proxy 127.0.0.1:3001\n}\n`);
fs.writeFileSync(path.join(OUT, "Caddyfile"), caddy.join("\n"));

// ---- pm2
const procs = [];
for (const s of stores) {
  procs.push(`api(${JSON.stringify(`api-${s.slug}`)}, ${s.apiPort}, ${JSON.stringify(s.database)}, ${redisDb(s)})`);
  procs.push(`web(${JSON.stringify(`web-${s.slug}`)}, ${JSON.stringify(dirOf(s))}, ${s.webPort})`);
}
procs.push(`web("admin", "admin", 3001)`);
fs.writeFileSync(path.join(OUT, "ecosystem.config.cjs"), `// generated by deploy/generate.mjs
const fs = require("fs");
const sec = Object.fromEntries(fs.readFileSync("/srv/shop/secrets.env", "utf8").split("\\n").filter((l) => /^[A-Z_]+=/.test(l)).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]));
const api = (name, port, db, redis) => ({ name, cwd: "${APP}/apps/api", script: "node", args: "--import tsx src/server.ts", max_memory_restart: "600M",
  env: { NODE_ENV: "production", PORT: port, DATABASE_URL: "postgres://shop:" + sec.DB_PASSWORD + "@127.0.0.1:5432/" + db, REDIS_URL: "redis://127.0.0.1:6379/" + redis,
    JWT_SECRET: sec.JWT_SECRET, PAYMENT_WEBHOOK_SECRET: sec.PAYMENT_WEBHOOK_SECRET, ENABLED_PAYMENT_METHODS: "COD" } });
const web = (name, dir, port) => ({ name, cwd: "${APP}/apps/" + dir, script: require.resolve("next/dist/bin/next", { paths: ["${APP}/apps/" + dir] }), args: "start -p " + port + " -H 127.0.0.1", max_memory_restart: "700M", env: { NODE_ENV: "production" } });
module.exports = { apps: [
  ${procs.join(",\n  ")},
] };
`);

// ---- hosts (the shops call their API by its public name; on the server that name points to this machine, so no trip over the internet)
fs.writeFileSync(path.join(OUT, "hosts.txt"), `127.0.0.1 ${[...stores.map(apiHost), adminHost, ...stores.map(host)].join(" ")}\n`);

// ---- stores.json for scripts/store-links.ts (links between the shops) and the admin's list
fs.writeFileSync(path.join(OUT, "stores.json"), JSON.stringify({ domain, stores }, null, 2));
fs.writeFileSync(path.join(OUT, "admin-stores.json"), JSON.stringify(stores.map((s) => ({ slug: s.slug, name: s.name, api: `https://${apiHost(s)}/api/v1` })), null, 2));

// ---- addresses baked into every build (NEXT_PUBLIC_*) and the list of apps to build
const lines = [];
for (const s of stores) {
  fs.writeFileSync(path.join(OUT, "env", `${dirOf(s)}.env.production`), `NEXT_PUBLIC_API_URL=https://${apiHost(s)}/api/v1\nNEXT_PUBLIC_SITE_URL=https://${host(s)}\nNEXT_PUBLIC_STORE_URL=https://${host(s)}\n`);
  lines.push(dirOf(s));
}
const main = stores.find((s) => s.slug === "main") ?? stores[0];
fs.writeFileSync(path.join(OUT, "env", "admin.env.production"), `NEXT_PUBLIC_API_URL=https://${apiHost(main)}/api/v1\nNEXT_PUBLIC_STORE_URL=https://${host(main)}\n`);
lines.push("admin");
fs.writeFileSync(path.join(OUT, "apps.txt"), lines.join("\n") + "\n");
console.log(`written to ${OUT}: ${stores.map((s) => `${s.slug} -> https://${host(s)} (API ${apiHost(s)})`).join("; ")}; admin https://${adminHost}`);
